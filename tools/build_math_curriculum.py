"""Build original middle-school review lessons; first five lessons stay intact."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
bank_path = ROOT / 'data/math/lessons.json'
bank = json.loads(bank_path.read_text(encoding='utf-8'))
lessons = bank['lessons'][:5]

def add(title, unit, concept, method, example, rows):
    questions = []
    for i, line in enumerate(rows.strip().splitlines()):
        prompt, correct, b, c, d, explanation = line.split('|')
        options = [correct, b, c, d]
        shift = (len(lessons) + i) % 4
        options = options[-shift:] + options[:-shift] if shift else options
        questions.append(dict(level='巩固' if i < 5 else '挑战', point=min(i // 2, 2), text=prompt,
                              options=options, answer=shift, explanation=explanation))
    assert len(questions) == 6, title
    lessons.append(dict(id=f'review-{len(lessons)+1:02d}', title=title, unit=unit,
                        materials=[dict(title='知识与适用条件', text=concept),
                                   dict(title='解题方法与易错点', text=method),
                                   dict(title='讲解例题与迁移', text=example)], questions=questions))

