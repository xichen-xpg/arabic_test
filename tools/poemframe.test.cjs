const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs'), path = require('node:path'), http = require('node:http');
const assert = require('node:assert/strict'), vm = require('node:vm');
const { pathToFileURL } = require('node:url');
const { execFileSync } = require('node:child_process');
const schedule = require('../games/poem-schedule.js');
const root = path.resolve(__dirname, '..');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'games/daily-poems.js'), 'utf8'), context);
const works = JSON.parse(JSON.stringify(context.window.dailyPoemWorks));
const server = http.createServer((req, res) => {
  const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); res.end(); return; }
  res.setHeader('Content-Type', ({ '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png' })[path.extname(file)] || 'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});
(async () => {
  assert.equal(works.length, 74);
  const texts = works.map(work => (work.fullText.join('').match(/\p{Script=Han}/gu) || []).join(''));
  assert.equal(new Set(texts).size, works.length);
  assert.ok(texts.every(text => text.length > 0 && text.length <= 60));
  assert.deepEqual([...new Set(works.slice(29).map(work => work.genre))].sort(), ['文', '词', '诗', '现代诗'].sort());
  assert.ok(works.slice(29).every(work => new URL(work.sourceUrl).protocol === 'https:'));
  const additions = works.slice(53), prose = additions.filter(work => work.genre === '文');
  assert.equal(prose.length, 12);
  assert.ok(new Set(prose.map(work => work.author)).size >= 10);
  assert.equal(additions.filter(work => work.genre === '现代诗').length, 7);
  assert.ok(additions.every(work => Boolean(work.excerpt) === work.title.includes('（节选）')));
  const posterWorks = (await import(pathToFileURL(path.join(root, 'poemframe/materials/gaokao_works.js')).href)).gaokaoWorks;
  assert.deepEqual(JSON.parse(JSON.stringify(posterWorks)), works);
  const today = schedule.today(), selected = works[schedule.indexForDate(today, works.length)];
  const output = execFileSync(process.execPath, ['poemframe/scripts/generate_daily_poem_image.js', '--dry-run'], { cwd: root, encoding: 'utf8' });
  assert.ok(output.includes(`Selected: ${selected.title} / ${selected.author}`));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const base = `http://127.0.0.1:${server.address().port}`;
    await page.goto(base + '/games/arabic-test.html#poems');
    await page.locator('.poem-poster-link').waitFor();
    const dates = Array.from({ length: works.length * 2 }, (_, i) => new Date(Date.parse('2026-05-19T00:00:00Z') + i * 86400000).toISOString().slice(0, 10));
    const questions = await page.evaluate(dates => dates.map(date => dailyPoemQuestions(date).map(q => q.title)), dates);
    questions.forEach((titles, i) => assert.deepEqual(titles, [works[schedule.indexForDate(dates[i], works.length)].title]));
    await page.selectOption('#categorySelect', 'source:daily-english');
    assert.equal(await page.locator('.poem-poster-link').isVisible(), false);
    const metadata = { date: today, title: selected.title, author: selected.author, fullText: selected.fullText };
    await page.route('**/poemframe/daily-poem.json', route => route.fulfill({ json: metadata }));
    await page.route('**/*.png?date=*', route => route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5XcAAAAASUVORK5CYII=', 'base64') }));
    await page.goto(base + '/poemframe/index.html');
    await page.locator('#poster').waitFor();
    assert.equal(await page.locator('#original').isVisible(), false);
    metadata.date = '2026-01-01';
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('尚未生成'));
    assert.equal(await page.locator('#poster').isVisible(), false);
    assert.equal(await page.locator('#title').textContent(), selected.title);
    metadata.date = today; metadata.fullText = ['Outdated text'];
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('尚未生成'));
    assert.equal(await page.locator('#poster').isVisible(), false);
    fs.mkdirSync(path.join(root, '.math-test'), { recursive: true });
    await page.screenshot({ path: path.join(root, '.math-test/poemframe-preview.png'), fullPage: true });
    await page.emulateMedia({ media: 'print' });
    assert.equal(await page.locator('#original').isVisible(), true);
    assert.equal(await page.locator('nav').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log(`Passed ${works.length}-work limits, sources, prose diversity, excerpt labels, shared selection, poster matching and printing.`);
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); server.close(); process.exitCode = 1; });
